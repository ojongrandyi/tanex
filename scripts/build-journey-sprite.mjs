// Regenerates src/pages/home/journeySprite.ts from design/sprite.js (the approved C.1 drawings).
// Run: node scripts/build-journey-sprite.mjs
// The design file injects its sprite into a page; here it runs against a tiny stand-in document
// that captures the CSS and SVG it would insert. UI icons are dropped (the site uses lucide-react).
import fs from 'node:fs';

let css = '';
let html = '';
const doc = {
  createElement: () => ({ setAttribute() {}, style: {}, set textContent(v) { css = v; }, set innerHTML(v) { html = v; } }),
  head: { appendChild() {} },
  body: { firstChild: null, insertBefore() {} },
  documentElement: {},
};
new Function('document', fs.readFileSync('design/sprite.js', 'utf8'))(doc);

html = html
  .replace(/<symbol id="i-[^"]+"[\s\S]*?<\/symbol>/g, '')
  .replace('<svg xmlns="http://www.w3.org/2000/svg">', '')
  .replace(/<\/svg>$/, '')
  .replace('../Public/brand/logo-wordmark.png', '__LOGO__');

const out = `// Generated by scripts/build-journey-sprite.mjs from design/sprite.js (approved C.1 direction):
// flat brand-palette illustrations used as the homepage chapter posters until the 3D Stage
// replaces them (MOTION_3D_SPEC §5, §8). Static markup we wrote (no user input), injected once by
// <JourneySprite>. Colours are CSS custom properties so one drawing works on cream and on
// chocolate. Decorative: always aria-hidden. Don't edit by hand; edit design/sprite.js and rerun.

export const JOURNEY_SPRITE_CSS = ${JSON.stringify(css)};

/** Symbols and defs; __LOGO__ is replaced with the wordmark URL at render time. */
export const JOURNEY_SPRITE_SYMBOLS = ${JSON.stringify(html)};
`;
fs.writeFileSync('src/pages/home/journeySprite.ts', out);
console.log(`journeySprite.ts: ${css.length} B css, ${html.length} B symbols`);
