// Builds the globe's dot map for the homepage Stage (MOTION_3D_SPEC §4: "Globe: cream sphere,
// chocolate dotted continents", ≤ 25 KB). Points are spread evenly over the sphere (Fibonacci
// lattice); a point is land when it falls inside a country of Natural Earth's 1:110m Admin 0
// countries (public domain, https://www.naturalearthdata.com). The output is one bit per point
// plus the points inside Cameroon, written to src/motion/stage/globeDots.ts.
//
// Usage: node scripts/build-globe-dots.mjs <ne_110m_admin_0_countries.geojson>
// The GeoJSON is read as data only; it is not kept in the repository.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Points on the whole sphere. Must match DOT_COUNT's use in src/motion/stage/globe.ts. */
const COUNT = 24000;
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'motion', 'stage', 'globeDots.ts');

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-globe-dots.mjs <ne_110m_admin_0_countries.geojson>');
  process.exit(1);
}
const data = JSON.parse(fs.readFileSync(source, 'utf8'));

/** Polygons as arrays of rings ([lon, lat] points), with a bounding box for a quick reject. */
function polygonsOf(feature) {
  const g = feature.geometry;
  if (!g) return [];
  const list = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  return list.map((rings) => {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of rings[0]) {
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    return { rings, minX, minY, maxX, maxY };
  });
}

/** Even-odd ray cast over every ring (outer + holes). */
function inside(polygons, lon, lat) {
  for (const p of polygons) {
    if (lon < p.minX || lon > p.maxX || lat < p.minY || lat > p.maxY) continue;
    let odd = false;
    for (const ring of p.rings) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) odd = !odd;
      }
    }
    if (odd) return true;
  }
  return false;
}

const iso = (f) => f.properties.ISO_A2_EH ?? f.properties.ISO_A2;
const land = data.features.flatMap(polygonsOf);
const cameroonFeature = data.features.find((f) => iso(f) === 'CM');
if (!cameroonFeature) throw new Error('Cameroon (CM) not found in the source');
const cameroon = polygonsOf(cameroonFeature);

// Same lattice as globe.ts: y from +1 to -1, golden-angle turns; lon 0 faces +Z.
const GOLDEN = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(COUNT / 8));
const cm = [];
let landCount = 0;
for (let i = 0; i < COUNT; i++) {
  const y = 1 - (2 * i + 1) / COUNT;
  const r = Math.sqrt(1 - y * y);
  const x = Math.cos(GOLDEN * i) * r;
  const z = Math.sin(GOLDEN * i) * r;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = (Math.atan2(x, z) * 180) / Math.PI;
  if (inside(land, lon, lat)) {
    bits[i >> 3] |= 1 << (i & 7);
    landCount++;
    if (inside(cameroon, lon, lat)) cm.push(i);
  }
}

const out = `// Generated by scripts/build-globe-dots.mjs from Natural Earth 1:110m Admin 0 countries
// (public domain). Do not edit by hand: re-run the script.
// ${landCount} land points of ${COUNT}; ${cm.length} in Cameroon.

/** Points on the whole sphere (Fibonacci lattice, see globe.ts). */
export const DOT_COUNT = ${COUNT};
/** One bit per point, little-endian within each byte: 1 = land. Base64. */
export const LAND_BITS = '${Buffer.from(bits).toString('base64')}';
/** Points inside Cameroon (lit on the globe). */
export const CAMEROON_DOTS: readonly number[] = [${cm.join(', ')}];
`;
fs.writeFileSync(OUT, out);
console.log(`${landCount} land points of ${COUNT}, ${cm.length} in Cameroon -> ${path.relative(process.cwd(), OUT)} (${out.length} bytes)`);
