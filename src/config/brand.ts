// "09:00" -> "9:00 AM". English; pages in a chosen language use formatOpeningHoursIn
// (src/i18n/format.ts), which also writes the French "9 h 00 – 16 h 00".
function formatClock(hhmm: string): string {
  const [h, m] = hhmm.split(':').map(Number);
  return `${((h + 11) % 12) + 1}:${String(m).padStart(2, '0')} ${h < 12 ? 'AM' : 'PM'}`;
}

/** Opening hours for display: "24/7", or a range such as "9:00 AM – 4:00 PM". */
export function formatOpeningHours(hours: OpeningHours = OPENING_HOURS): string {
  if (hours.allDay) return '24/7';
  return `${formatClock(hours.opens)} – ${formatClock(hours.closes)}`;
}

/**
 * Display form of a phone number. Cameroon numbers (+237 / 00237 and 9 digits) are grouped as
 * "+237 651 05 93 45"; anything else is returned trimmed, as entered.
 */
export function formatPhone(phone: string): string {
  const trimmed = (phone || '').trim();
  const compact = trimmed.replace(/[\s().-]/g, '');
  const cm = /^(?:\+|00)237(\d{9})$/.exec(compact);
  if (!cm) return trimmed;
  const n = cm[1];
  return `+237 ${n.slice(0, 3)} ${n.slice(3, 5)} ${n.slice(5, 7)} ${n.slice(7)}`;
}

