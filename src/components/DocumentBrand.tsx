// Shared parts of every generated document (docs/CONTENT.md §11): the brand header block, the
// tracking ID line, the tamper-evident pouch line and the legal footer. Used by the admin
// Document Center papers (which become the PDFs).
import React from 'react';
import { COMPANY_SHORT, DOMAIN, LEGAL_NAME, LOGO, LOGO_ALT, LOGO_HEIGHT, LOGO_WIDTH } from '../config/brand';
import { useCompanyContact } from '../utils/useCompanyContact';
import type { DocumentType } from '../types/admin';
import type { TransportMode } from '../shared/transportMode';
import { pagePath } from '../router/routes';
import './DocumentBrand.css';

/** §11 title for a document type. A transport document is an air waybill when the main leg flies. */
export function documentTitle(docType: DocumentType, mode?: TransportMode): string {
  switch (docType) {
    case 'BOL':
      return mode === 'Air' ? 'Air Waybill / House Waybill' : 'Bill of Lading';
    case 'INVOICE':
      return 'Commercial Invoice';
    case 'SHIPPING_LABEL':
      return 'Shipping Label';
    case 'RECEIPT':
      return 'Shipment Receipt';
    case 'INSURANCE':
      return 'Certificate of Cargo Insurance';
    default:
      return 'Shipment Document';
  }
}

/** Logo, legal name and "{address} · {email} · {domain}" (the address is left out when empty). */
export const DocumentHeaderBrand: React.FC<{ className?: string }> = ({ className = '' }) => {
  const { address, email } = useCompanyContact();
  return (
    <div className={`ngf-doc-brand ${className}`}>
      <img src={LOGO} width={LOGO_WIDTH} height={LOGO_HEIGHT} alt={LOGO_ALT} className="doc-preview-logo-img" />
      <strong className="ngf-doc-legal-name">{LEGAL_NAME}</strong>
      <span className="ngf-doc-contact-line">{[address, email, DOMAIN].filter(Boolean).join(' · ')}</span>
    </div>
  );
};

export const DocumentIdLine: React.FC<{ trackingId: string }> = ({ trackingId }) => (
  <div className="ngf-doc-id-line">
    Tracking ID / Waybill No.: <strong className="font-mono">{trackingId}</strong>
  </div>
);

export const DocumentPouchLine: React.FC<{ sealNumber: string }> = ({ sealNumber }) => (
  <div className="ngf-doc-pouch-line">
    {COMPANY_SHORT} Tamper-Evident Document Pouch · Seal No. <strong className="font-mono">{sealNumber}</strong>
  </div>
);

// CONTENT §11 footer: {DOMAIN}/legal/shipping-terms (always the English path on printed papers).
const SHIPPING_TERMS_PATH = pagePath('legal', 'shipping-terms');

export const DocumentLegalFooter: React.FC = () => (
  <p className="ngf-doc-legal-footer">
    This document was generated by {LEGAL_NAME}. Carriage is subject to {COMPANY_SHORT}'s Shipping Terms at {DOMAIN}{SHIPPING_TERMS_PATH}.
  </p>
);
